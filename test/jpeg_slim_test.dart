import 'dart:typed_data';
import 'package:flutter_test/flutter_test.dart';
import 'package:relay_chat/utils/jpeg_slim.dart';

void main() {
  group('JpegSlim', () {
    test('drops APPn and COM segments, keeps tables and scan data untouched', () {
      final input = Uint8List.fromList([
        0xFF, 0xD8,
        0xFF, 0xE0, 0x00, 0x06, 0x4A, 0x46, 0x49, 0x46, // APP0 (JFIF)
        0xFF, 0xE2, 0x00, 0x05, 0x01, 0x02, 0x03, // APP2 (ICC profile)
        0xFF, 0xFE, 0x00, 0x04, 0x68, 0x69, // COM
        0xFF, 0xDB, 0x00, 0x04, 0xAA, 0xBB, // DQT  (kept)
        0xFF, 0xC0, 0x00, 0x03, 0xCC, // SOF0 (kept)
        0xFF, 0xDA, 0x00, 0x03, 0xDD, // SOS header (kept)
        0x11, 0xFF, 0x00, 0x22, // entropy data incl. a stuffed 0xFF00 (kept)
        0xFF, 0xD9, // EOI
      ]);
      final expected = <int>[
        0xFF, 0xD8,
        0xFF, 0xDB, 0x00, 0x04, 0xAA, 0xBB,
        0xFF, 0xC0, 0x00, 0x03, 0xCC,
        0xFF, 0xDA, 0x00, 0x03, 0xDD,
        0x11, 0xFF, 0x00, 0x22,
        0xFF, 0xD9,
      ];
      expect(JpegSlim.strip(input), expected);
    });

    test('non-JPEG and truncated data are returned unchanged', () {
      final notJpeg = Uint8List.fromList([1, 2, 3, 4, 5, 6]);
      expect(JpegSlim.strip(notJpeg), notJpeg);

      final truncated = Uint8List.fromList([0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x50, 1, 2]);
      expect(JpegSlim.strip(truncated), truncated);
    });
  });
}
